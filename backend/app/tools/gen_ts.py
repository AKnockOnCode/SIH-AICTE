"""Generate TypeScript API types for the frontend from the live OpenAPI document.

    python -m app.tools.gen_ts            # writes ../frontend/src/api/types.gen.ts
    python -m app.tools.gen_ts --check    # exit 1 if the committed file is stale

Response schemas become interfaces whose properties are always present (the server always
serialises every field); request-body schemas keep optional properties optional.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

OUT = Path(__file__).resolve().parents[3] / "frontend" / "src" / "api" / "types.gen.ts"
HEADER = ("// AUTO-GENERATED by `python -m app.tools.gen_ts` from the backend OpenAPI document.\n"
          "// Do not edit by hand; re-run the generator after changing backend schemas.\n"
          "/* eslint-disable */\n\n")


def _ref_name(ref: str) -> str:
    return ref.rsplit("/", 1)[-1]


def _ident(name: str) -> str:
    return re.sub(r"\W", "_", name)


def ts_type(s: dict[str, Any] | bool) -> str:
    if s is True or s == {}:
        return "any"
    if s is False:
        return "never"
    assert isinstance(s, dict)
    if "$ref" in s:
        return _ident(_ref_name(s["$ref"]))
    if "const" in s:
        return json.dumps(s["const"])
    if "enum" in s:
        return " | ".join(json.dumps(v) for v in s["enum"])
    for key in ("anyOf", "oneOf"):
        if key in s:
            parts = []
            for sub in s[key]:
                t = ts_type(sub)
                if t not in parts:
                    parts.append(t)
            return " | ".join(parts)
    if "allOf" in s and len(s["allOf"]) == 1:
        return ts_type(s["allOf"][0])
    t = s.get("type")
    if isinstance(t, list):
        return " | ".join(ts_type({**s, "type": x}) for x in t)
    if t == "string":
        return "string"
    if t in ("integer", "number"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        if "prefixItems" in s:
            return "[" + ", ".join(ts_type(x) for x in s["prefixItems"]) + "]"
        inner = ts_type(s.get("items", {}))
        return f"Array<{inner}>"
    if t == "object" or "properties" in s or "additionalProperties" in s:
        if "properties" in s:
            return _inline_object(s, output=True)
        ap = s.get("additionalProperties", True)
        return f"Record<string, {ts_type(ap) if isinstance(ap, dict) else 'any'}>"
    return "any"


def _inline_object(s: dict[str, Any], *, output: bool) -> str:
    req = set(s.get("required", []))
    fields = []
    for name, sub in s.get("properties", {}).items():
        opt = "" if (output or name in req) else "?"
        fields.append(f"{json.dumps(name) if not name.isidentifier() else name}{opt}: {ts_type(sub)}")
    return "{ " + "; ".join(fields) + " }"


def _refs(node: Any, acc: set[str]) -> None:
    if isinstance(node, dict):
        if "$ref" in node:
            acc.add(_ref_name(node["$ref"]))
        for v in node.values():
            _refs(v, acc)
    elif isinstance(node, list):
        for v in node:
            _refs(v, acc)


def _closure(names: set[str], schemas: dict[str, Any]) -> set[str]:
    seen: set[str] = set()
    stack = list(names)
    while stack:
        n = stack.pop()
        if n in seen or n not in schemas:
            continue
        seen.add(n)
        acc: set[str] = set()
        _refs(schemas[n], acc)
        stack.extend(acc - seen)
    return seen


def generate(spec: dict[str, Any]) -> str:
    schemas = spec["components"]["schemas"]
    input_roots: set[str] = set()
    for ops in spec["paths"].values():
        for op in ops.values():
            body = op.get("requestBody", {}).get("content", {}).get("application/json", {}).get("schema")
            if body:
                _refs(body, input_roots)
    inputs = _closure(input_roots, schemas)
    lines = [HEADER]
    for name in sorted(schemas):
        s = schemas[name]
        output = name not in inputs
        doc = s.get("description")
        if doc:
            lines.append("/** " + " ".join(doc.split()).replace("*/", "* /") + " */")
        if "properties" in s:
            req = set(s.get("required", []))
            lines.append(f"export interface {_ident(name)} {{")
            for pname, sub in s["properties"].items():
                opt = "" if (output or pname in req) else "?"
                key = pname if pname.isidentifier() else json.dumps(pname)
                desc = sub.get("description") if isinstance(sub, dict) else None
                if desc:
                    lines.append(f"  /** {' '.join(desc.split())} */")
                lines.append(f"  {key}{opt}: {ts_type(sub)};")
            lines.append("}\n")
        else:
            lines.append(f"export type {_ident(name)} = {ts_type(s)};\n")
    # Endpoint catalogue: method + path -> response type, plus required permission.
    lines.append("export const ENDPOINT_PERMISSIONS: Record<string, string | null> = {")
    for path, ops in spec["paths"].items():
        for method, op in ops.items():
            lines.append(f"  {json.dumps(method.upper() + ' ' + path)}: {json.dumps(op.get('x-permission'))},")
    lines.append("};\n")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--out", type=Path, default=OUT)
    args = ap.parse_args()
    from ..main import create_app_spec

    text = generate(create_app_spec())
    if args.check:
        current = args.out.read_text(encoding="utf-8") if args.out.exists() else ""
        if current != text:
            print(f"{args.out} is stale; run python -m app.tools.gen_ts", file=sys.stderr)
            return 1
        print("types up to date")
        return 0
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8")
    print(f"wrote {args.out} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
